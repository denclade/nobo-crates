//! The header that makes a mirror file a *subscription*.
//!
//! What an entry looks like is the mirror format's business and shared
//! with the CalDAV side (see nobo_calendar_mirror::org). What is here is
//! the half only an ICS feed has: the header this feature reads its
//! subscriptions back out of.

use crate::model::{CalendarEvent, CalendarSubscription};
use crate::registry;
use nobo_calendar_mirror::org::render_events;

/// The whole file for one calendar. Regenerated in full on every refresh,
/// never patched -- the remote feed is the only source of truth, so there
/// is nothing local worth merging.
///
/// The header is not decoration: it IS the subscription (see
/// nobo_calendar::registry). Name, feed URL and the on/off state are read
/// back out of it, which is why there is no calendar list in settings.json
/// any more -- and why a calendar added on one device simply appears on
/// the next once the vault has synced.
pub fn render_calendar(subscription: &CalendarSubscription, events: &[CalendarEvent]) -> String {
    let mut out = String::new();
    out.push_str(&format!("#+TITLE: {}\n", subscription.name));
    // What makes the file read-only, and the only thing that does: the
    // declaration travels with the file, so the rule survives a move or a
    // sync to another device (see core::file_kind).
    out.push_str(&format!("{}\n", crate::MIRROR_KIND.declaration()));
    out.push_str(&format!("{} {}\n", registry::URL_KEYWORD, subscription.url));
    // Only written when it is off: absent means on, so an ordinary
    // calendar's header stays as short as it was.
    if !subscription.enabled {
        out.push_str(&format!("{} {}\n", registry::ENABLED_KEYWORD, registry::DISABLED_VALUE));
    }
    if let Some(color) = &subscription.color {
        out.push_str(&format!("{} {color}\n", crate::model::COLOR_KEYWORD));
    }
    // Only when it is not the default, for the same reason as the enabled
    // line above: an ordinary calendar's header stays short.
    if subscription.refresh != crate::model::RefreshInterval::default() {
        if let Ok(serde_json::Value::String(value)) = serde_json::to_value(subscription.refresh) {
            out.push_str(&format!("{} {value}\n", registry::REFRESH_KEYWORD));
        }
    }
    // A vault is also just files -- somebody will open one in Emacs.
    //
    // English for every device and not localised, for the reason
    // caldav::registry::header spells out: file content that syncs
    // between devices with independent language settings must not depend
    // on either device's.
    out.push_str("#+COMMENT: Generated by nobo from an ICS subscription. Changes are lost on the next refresh.\n\n");
    out.push_str(&render_events(events));
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::registry;

    /// The header IS the subscription: name, feed URL and the on/off state
    /// are read back out of it (see registry), and the type declaration is
    /// what makes the file read-only in the first place.
    #[test]
    fn the_file_names_its_calendar_and_warns_that_it_is_generated() {
        let subscription = registry::subscription_for("Arbeit", "https://example.com/cal.ics");

        let rendered = render_calendar(&subscription, &[]);

        assert!(rendered.starts_with("#+TITLE: Arbeit\n"), "{rendered}");
        assert!(rendered.contains("#+COMMENT:"), "{rendered}");
        assert_eq!(nobo_core::core::file_kind::from_lines(&rendered.lines().collect::<Vec<_>>()), crate::MIRROR_KIND,);
    }
}
